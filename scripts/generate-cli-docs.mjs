import { readFile, writeFile } from 'node:fs/promises';
import { Buffer } from 'node:buffer';
import { resolve } from 'node:path';
import { format } from 'prettier';

const root = resolve(new URL('..', import.meta.url).pathname);
const registryPath = resolve(root, 'apps/lab-cli/src/command-registry.ts');
const outputPath = resolve(root, 'docs/cli-reference.md');
const check = process.argv.includes('--check');

async function loadRegistry() {
  const source = await readFile(registryPath, 'utf8');
  const executable = source
    .replace(/export interface [\s\S]*?\n}\n/g, '')
    .replace(/const COMMON_EXIT_CODES:[^=]+=/, 'const COMMON_EXIT_CODES =')
    .replace(
      /export function createCommandRegistry\(\): readonly CliCommandDefinition\[]/,
      'function createCommandRegistry()',
    )
    .concat('\nexport { createCommandRegistry };\n');
  const encoded = Buffer.from(executable, 'utf8').toString('base64');
  const mod = await import(`data:text/javascript;base64,${encoded}`);
  return mod.createCommandRegistry();
}

function inlineList(values) {
  return values.length === 0 ? 'None' : values.map((value) => `\`${value}\``).join(', ');
}

function render(registry) {
  const lines = [
    '# Cashu Fault Lab CLI Reference',
    '',
    '<!-- Generated by scripts/generate-cli-docs.mjs. Do not edit by hand. -->',
    '',
    'Global diagnostic option: `--json` before a command emits machine-readable diagnostics for command-level failures.',
    '',
  ];

  for (const command of registry) {
    lines.push(`## \`${command.usage}\``, '', command.summary, '');
    if (command.arguments.length > 0) {
      lines.push('Arguments:');
      for (const argument of command.arguments) {
        lines.push(`- \`${argument.value}\`: ${argument.description}`);
      }
      lines.push('');
    }
    if (command.options.length > 0) {
      lines.push('Options:');
      for (const option of command.options) {
        const suffix = [
          option.defaultValue === undefined ? '' : ` Default: \`${option.defaultValue}\`.`,
          option.choices === undefined ? '' : ` Choices: ${inlineList(option.choices)}.`,
        ].join('');
        lines.push(`- \`${option.flags}\`: ${option.description}${suffix}`);
      }
      lines.push('');
    }
    lines.push(`Modes: ${inlineList(command.modes)}`);
    lines.push(`Environment: ${inlineList(command.env)}`);
    lines.push(`Artifacts: ${inlineList(command.artifacts)}`);
    lines.push('');
    lines.push('Exit Codes:');
    for (const exitCode of command.exitCodes) {
      lines.push(`- \`${exitCode.code}\`: ${exitCode.meaning}`);
    }
    lines.push('');
    lines.push('Examples:');
    for (const example of command.examples) {
      lines.push(`- \`${example}\``);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const expected = await format(render(await loadRegistry()), { parser: 'markdown' });
if (check) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== expected) {
    console.error('docs/cli-reference.md is out of date. Run pnpm docs:cli.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected, 'utf8');
}
